"""
ACD via the DUAL of the multivariate-Coppersmith (MP) lattice.

attacks/acd/mp.py solves ACD the *primal* way: build the MP shift lattice, LLL-reduce
it, reconstruct short polynomials, and solve them with a Groebner basis.  This module
keeps the same setup and finish but replaces the middle with a dual-lattice route.

Reused from mp.py (ACD-specific, unchanged): _build_shifts (the MP shift family),
small_roots.create_lattice / reduce_lattice, the |r_i| < R validity test, and the final
p = gcd(N, a - r) extraction.

New (the dual algorithm, ACD-agnostic): snf_congruence_kernel builds the dual lattice
{v : A v == 0 (mod M)} from the Smith normal form of the shift matrix A; the moment
balancing R^{t-deg} rescales it; and _moment_roots reads roots directly off the dual
moment vectors -- no Groebner basis.

ACD glue: the shifts vanish modulo the secret p^k, so we build the dual over the public
M = N^k instead (the device mp.py uses for its Howgrave-Graham bound).  The moment vector
M(r) then lies in the p^k-kernel; a scalar multiple q0^k * M(r) lies in the N^k-kernel,
and _moment_roots decodes by scale-invariant coordinate ratios, so the q0^k cancels.
"""
import logging
import os
import sys
from itertools import product
from math import gcd

from sage.all import ZZ
from sage.all import diagonal_matrix
from sage.all import gcd as sage_gcd

path = os.path.dirname(os.path.dirname(os.path.realpath(os.path.abspath(__file__))))
if path not in sys.path:
    sys.path.insert(0, path)

from shared import small_roots
from shared.reduction import reduce_integer_basis


def _build_shifts(pr, x, N, a, t, k):
    """[REUSED from mp.py] The exact MP shift family of attacks/acd/mp.py:
        N^l * prod_i (x_i - a_i)^{i_i},  sum i_i <= t,  l = max(k - sum i_i, 0).

    These are the {f_i}.  At the hidden root r they all vanish modulo p^k, because each
    (x_i - a_i) -> -p*q_i contributes a factor p and N^l = (p*q0)^l contributes l more, for
    a total exponent sum i_i + l >= k.  This is identical to mp.py; nothing new here.
    """
    shifts = []
    for i in product(*[range(t + 1) for _ in x]):
        if sum(i) <= t:
            l = max(k - sum(i), 0)
            fi = N ** l
            for m in range(len(i)):
                fi *= (x[m] - a[m]) ** i[m]
            shifts.append(fi)
    return shifts


def snf_congruence_kernel(A, modulus):
    """[New -- core of our algorithm] Row basis of the DUAL / congruence-kernel lattice
        L = { v in Z^n : A v == 0 (mod modulus) }
    from the Smith normal form of A.  Generic (integer matrix + modulus; ACD never appears).

    With unimodular U, V giving U A V = S = diag(d_1, .., d_r, 0, ..) (elementary divisors
    d_i), the kernel is generated by  diag(mult_i) * V^T  with  mult_i = M / gcd(M, d_i)  (and
    1 on the free coordinates d_i = 0).  For the graded MP matrix the divisors 1, N, N^2, ..
    become multipliers N^k, N^{k-1}, .. 1 -- the primal graded diagonal appears FLIPPED in
    the dual.  V's entries are ~ those of A, so the basis is not reduced; the caller LLL-reduces it.
    """
    modulus = ZZ(modulus)
    n = A.ncols()
    # Smith Normal Form: U*A*V = S (diagonal), U and V unimodular.  We only need V (and the
    # divisors S[i,i]); U is not used.
    S, U, V = A.smith_form()
    divs = [ZZ(S[i, i]) for i in range(min(A.nrows(), n))]
    mult = []
    for i in range(n):
        # Coordinates beyond the rank are free (d_i = 0 -> multiplier 1); otherwise the
        # dual multiplier is M / gcd(M, d_i) (the complementary / flipped divisor).
        d = divs[i] if i < len(divs) else ZZ(0)
        mult.append(ZZ(1) if d == 0 else modulus // sage_gcd(modulus, d))
    # Basis rows = mult_i * (i-th column of V) = rows of diag(mult) * V^T.
    return diagonal_matrix(ZZ, mult) * V.transpose()


def attack(N, a, rho, t=1, k=1, roots_method="groebner", dual_modulus="N", p=None,
           kernel_method="snf", use_flatter=False):
    """
    Solve ACD by building the MP (Coppersmith) lattice exactly as attacks/acd/mp.py, then
    recovering the root from the SNF DUAL / congruence-kernel lattice instead of reducing
    the primal lattice and running a Groebner basis.

    This function is the WRAPPER that stitches together:
        ACD setup (reused from mp.py)  ->  our dual algorithm (new)  ->  ACD finish (reused).

    dual_modulus:
        "N": public N^k dual  { v : A v == 0 mod N^k }  -- the real attack.
        "p": oracle p^k dual (needs the secret p) -- diagnostic only, to confirm the dual
             MECHANISM recovers the root when handed the true (secret) modulus.

    :return: (p_recovered, r_list) or None.
    """
    # ---- [REUSED from mp.py] problem setup: ring, bounds, and the shift family {f_i} ----
    assert len(a) > 0, "At least one a value is required."
    assert t >= k, "t must be greater than or equal to k."

    R = 2 ** rho
    m = len(a)
    pr = ZZ[tuple(f"x{i}" for i in range(m))]
    x = pr.gens()
    X = [R] * m

    logging.debug("Generating MP shifts (mp.py style)...")
    shifts = _build_shifts(pr, x, N, a, t, k)

    # [REUSED fn / NEW usage] same create_lattice as mp.py, but with UNIT bounds so no
    # R^deg scaling is baked in: we want the raw coefficient matrix A of the {f_i}, because
    # the dual and its (opposite-direction) balancing are applied afterwards.  mp.py instead
    # passes X = [R]*m here to build the bound-scaled *primal* lattice.  This is the exact
    # point where the primal and dual routes diverge.
    A, monomials = small_roots.create_lattice(pr, shifts, [1] * m)

    # ---- [ACD GLUE] pick the dual modulus: public N^k for the real attack (see the module
    # docstring for why the p^k-kernel moment vector still decodes).  "p" is a test oracle.
    if dual_modulus == "N":
        M = ZZ(N) ** k
    elif dual_modulus == "p":
        assert p is not None, "oracle dual needs the secret p"
        M = ZZ(p) ** k
    else:
        raise ValueError(f"unknown dual_modulus {dual_modulus!r}")

    # ---- [NEW -- our algorithm] dual lattice -> balance -> reduce -> read the root -------
    # (1) Dual lattice L = { v : A v == 0 mod M }.  "snf" and "howell" give the SAME lattice
    # but different bases, and the basis matters downstream.  "snf" (default) is the
    # flip-the-divisors Smith-form basis, already well graded (~ N^k .. 1) so the reduction
    # is fast; "howell" builds faster but its raw HNF basis is LLL-hostile (~3x slower, times
    # out for m >= 6), so we keep snf.
    logging.debug(f"Building congruence-kernel dual mod {dual_modulus}^{k} ({kernel_method})...")
    if kernel_method == "snf":
        L = snf_congruence_kernel(A, M)
    else:
        from shared import dual_moment
        L = dual_moment.howell_congruence_kernel(A, M)

    # (2) DUAL/moment balancing: scale the column of monomial X^b by R^{t - deg b}.  Then the
    # target moment (Veronese) vector M(r)[b] = r^b * R^{t - deg b} has every coordinate on
    # the same scale ~ R^t, so LLL sees it as a genuinely short vector and returns it.  This
    # is the OPPOSITE of the R^{deg} bound scaling mp.py bakes into the primal lattice.
    scales = [ZZ(R) ** (t - monomial.degree()) for monomial in monomials]
    LB = L * diagonal_matrix(ZZ, scales)
    # (3) Use the same fpLLL backend and delta as the primal pipeline.
    LB = reduce_integer_basis(LB, use_flatter=use_flatter)

    # (4) The short dual vectors are the moment vectors of candidate roots (NOT polynomials
    # vanishing at the root), so _moment_roots yields the roots directly -- no Groebner.

    # ---- [REUSED from mp.py] identical to mp.py's ending, with _moment_roots (our moment
    # decoder) in the exact place of small_roots.find_roots (mp.py's Groebner root search):
    # pick the first candidate that is a valid small root and recover the prime from it.
    for roots in _moment_roots(LB, monomials, x, R, t):
        r = [roots[xi] for xi in x]
        if all(-R < ri < R for ri in r):
            # Each a[i] - r[i] = p * q_i, so g = gcd(N, a[0]-r[0], ..., a[m-1]-r[m-1])
            # = p * c, where c = gcd(q0, q_1, ...) is a small spurious cofactor (usually 1).
            # g is already a nontrivial factor of N -- that split is the cryptographic
            # output.  At these toy sizes we peel off the small c to report p exactly for
            # the equality check in run_acd.py; this prime_divisors() step is a validation
            # convenience, not part of the attack (at real sizes one returns g directly).
            g = gcd(N, *(a[i] - r[i] for i in range(len(a))))
            if not (1 < g < N):
                continue
            p_recovered = int(max(ZZ(g).prime_divisors()))
            return p_recovered, r

    return None


def _moment_roots(LB, monomials, x, R, t):
    """[New -- our algorithm] Generator of candidate roots read off the reduced dual basis --
    the dual-side analogue of small_roots.find_roots(), but with no Groebner basis.  Yields
    {x_i: r_i} dicts; attack() applies the same |r_i| < R check and gcd as mp.py.

    The planted target is the balanced moment (Veronese) vector v[b] = c * r^b * R^{t-deg b}.
    From the constant and degree-one coordinates,  r_i = R * v[x_i] / v[const], with the
    scalar c cancelling (which is why the public-N^k dual works: q0^k*M(r) decodes like M(r)).
    A row is kept only if it passes the full Veronese consistency  v[b] * R^{deg b} ==
    v[const] * r^b  over every monomial, rejecting a vector matching only the low-degree
    coordinates.  All reduced rows are scanned; the size test is left to attack().
    """
    pr = x[0].parent()
    one = pr(1)
    idx = {monomials[i]: i for i in range(len(monomials))}
    # We need the constant and all degree-one monomials present to read off r.
    if one not in idx or not all(xi in idx for xi in x):
        return
    for row in range(LB.nrows()):
        v = LB.row(row)
        v0 = ZZ(v[idx[one]])  # constant coordinate == c * R^t
        if v0 == 0:
            continue
        cand = []
        ok = True
        for xi in x:
            # r_i = R * v[x_i] / v[const]; the scalar c cancels here.  Must be integral.
            num = ZZ(R) * ZZ(v[idx[xi]])
            if num % v0 != 0:
                ok = False
                break
            cand.append(ZZ(num // v0))
        if not ok:
            continue
        # Full Veronese check: every coordinate must equal c * r^b, i.e. this row really is
        # (a scalar multiple of) the moment vector of the candidate root, not a coincidence.
        good = True
        for monomial in monomials:
            lhs = ZZ(v[idx[monomial]]) * (ZZ(R) ** monomial.degree())
            rhs = v0 * ZZ(monomial(*cand))
            if lhs != rhs:
                good = False
                break
        if good:
            yield {xi: ri for xi, ri in zip(x, cand)}
